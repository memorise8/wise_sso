def application_uuid() -> str:
    """Return a Prisma-compatible textual UUID generated by the application."""

    return str(uuid4())


def utc_now_ms() -> datetime:
    """Return UTC as a timezone-naive value truncated to PostgreSQL TIMESTAMP(3)."""

    now = datetime.now(UTC).replace(tzinfo=None)
    return now.replace(microsecond=(now.microsecond // 1_000) * 1_000)


